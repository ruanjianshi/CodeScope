const {buildCodeGraph}=require('./lib/code-graph');
const {buildLogicGraph,logicToDrawio,logicToSkeleton}=require('./lib/logic-graph');
const snippets=[{file:'a.c',name:'demo',fragments:[{label:'a.c',language:'c_cpp',code:'int foo(){bar();}\nint bar(){}\nint main(){foo();}'}]}];
let r=buildCodeGraph(snippets,{rootFunction:'',rootFile:'',depth:3,direction:'both'});
console.log('stats',JSON.stringify(r.stats));
console.log('symbols',JSON.stringify(r.symbols.map(s=>s.id)));
let foo=r.symbols.find(s=>s.name==='foo');
let rf=buildCodeGraph(snippets,{rootFunction:foo.id,depth:2,direction:'both'});
console.log('fnGraph',JSON.stringify(rf.functionGraph).slice(0,3000));
let lg=buildLogicGraph('int foo(){if(x){bar();}else{return 1;}}',{language:'c_cpp',name:'foo'});
console.log('logic',JSON.stringify(lg).slice(0,1200));
console.log('drawio head',logicToDrawio(lg,{title:'foo'}).slice(0,250));
console.log('skel',JSON.stringify(logicToSkeleton(lg,{language:'c_cpp',fnName:'foo'})));